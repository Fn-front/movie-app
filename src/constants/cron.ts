/**
 * 「ほぼ全滅」と見なす失敗率（#1354）
 *
 * 同期系サービスは**作品ごとに catch して処理を続ける**。1件の失敗で全体を
 * 止めない設計は妥当だが、そのせいで**全件失敗しても 200 / `success: true`**
 * で返り、#1353 で入れた通知にも Vercel のステータス監視にも現れなかった。
 *
 * ⚠️ **1件でも失敗したら通知、にはしない。** 作品側の事情（TMDb に無い・
 * 構造が変わった等）で恒常的に数件落ちるため、鳴り続けて無視されるようになる。
 * 無視されるアラートは無いのと同じ。
 *
 * 半分を境にしたのは、「個々の作品の事情」では説明がつかなくなる水準だから。
 * ここを超えるのは鍵の失効・外部APIの障害・レート制限といった**全体の問題**で、
 * どれも人が動かないと直らない。
 */
export const CRON_FAILURE_RATE_THRESHOLD = 0.5;
