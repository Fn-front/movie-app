/**
 * パスワードリセットの定数
 */

/**
 * リセットトークンの設定
 */
export const PASSWORD_RESET_CONFIG = {
  /**
   * トークンの有効期限（分）。
   *
   * メールの到達に時間がかかることもあるので短すぎてはいけないが、
   * 長いほど「受信箱を後から覗かれる」窓が広がる。
   */
  EXPIRY_MINUTES: 30,
  /**
   * 同一メールアドレスへの発行上限（回 / 窓）。
   *
   * メールボックスを守るための上限なので、識別子に送信元IPを混ぜない。
   * 混ぜるとIP数だけ掛け算できてしまい、保護の目的が壊れる（#641 と同じ理屈）。
   */
  REQUEST_LIMIT: { maxAttempts: 5, windowMinutes: 60 },
  /**
   * トークン検証の試行上限（回 / 窓）。
   *
   * トークンは256bitの乱数なので総当たりは成立しないが、
   * 大量の失敗リクエストを垂れ流させない。
   */
  CONFIRM_LIMIT: { maxAttempts: 10, windowMinutes: 15 },
} as const;

