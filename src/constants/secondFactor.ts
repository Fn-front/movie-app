/**
 * 二段階認証の第2要素に関する定数
 *
 * TOTP 固有の値（桁数・時間ステップ・リカバリーコードの形式）は
 * `src/constants/totp.ts` に置く。ここには**方式に依存しないもの**だけを置く。
 */

/**
 * 第2要素の方式
 *
 * `user_totp.method` の値。`user_id` が主キーで1ユーザー1件なので、
 * 方式はDB側で排他になる。
 */
export const SECOND_FACTOR_METHOD = {
  /** 認証アプリ（RFC 6238）。コードは端末内で計算されるため通信しない */
  TOTP: 'totp',
  /** メールのワンタイムコード */
  EMAIL_OTP: 'email_otp',
} as const;

export type SecondFactorMethod =
  (typeof SECOND_FACTOR_METHOD)[keyof typeof SECOND_FACTOR_METHOD];

/**
 * 第2要素コードの `otp_codes.action_type`
 *
 * ⚠️ **`OTP_ACTION`（src/constants/otp.ts）に足してはいけない。**
 *
 * `src/schema/otp.ts` の `PUBLIC_OTP_ACTIONS` は「公開ルートが受け付ける用途」で、
 * かつては `Object.values(OTP_ACTION)` から機械的に導出していた。そこに
 * `two_factor` が入ると `/api/auth/otp/send` と `/api/auth/otp/verify` が
 * これを受理する。
 *
 * `send` の action 分岐は宛先をセッションに固定する処理を `password_change` の
 * ときしか行わない（`route.ts:69`）。したがって `two_factor` は存在チェックも
 * 宛先固定も通らないまま送信へ到達し、**未認証のまま任意のアドレスへ
 * 自サービス名義の確認コードを送れる**状態になる（#641 で塞いだ穴の再発）。
 *
 * 第2要素のコードは `src/lib/auth/sendSecondFactorCode.ts` からしか作らない。
 * 呼び出せるのは認証済みの4経路だけ。
 */
export const TWO_FACTOR_OTP_ACTION = 'two_factor' as const;

export type TwoFactorOtpAction = typeof TWO_FACTOR_OTP_ACTION;

