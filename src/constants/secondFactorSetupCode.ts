/**
 * 二段階認証の設定に使う再認証コード（#1368）
 *
 * ⛔ **第2要素はセッションだけで自己登録できた。**
 *
 * `totp/setup` も `totp/enable` も `getAuthSession()` 以外に何も要求しないため、
 * セッションを奪った第三者が**被害者のアカウントに自分の第2要素を登録できる**。
 * 被害者にはメールが1通も届かない。
 *
 * 登録された第2要素は**乗っ取りの固定手段**になる。被害者が後からパスワードを
 * 変えても攻撃者の TOTP は残り、被害者は自分が設定していない第2要素を求められる。
 *
 * ⛔ **`OTP_ACTION` には足さない。** 足すと `/api/auth/otp/send` が受理し、
 * 未認証のまま任意のアドレスへ自サービス名義のコードを送れる（#641 / #1261）。
 *
 * ⚠️ **`two_factor` を流用しない。** あちらは「第2要素そのもののコード」で、
 * こちらは「第2要素を**設定してよいか**の再認証」。件名・本文が同じになると
 * 受信者が区別できず、#648 の設計が崩れる。
 */

