/**
 * 作品・利用者など「1件ずつ処理するもの」の集計（#1354）
 *
 * 同期系サービスは1件の失敗で全体を止めない。その判断は妥当だが、
 * **何件に対して何件失敗したか**を返していなかったため、全滅しても
 * 200 / `success: true` と区別がつかなかった。
 *
 * ⚠️ **既存の `errors: string[]` で代用しない。** あの配列には作品単位の
 * 失敗に混じって「UPSERT に失敗」「ページ取得に失敗」のような**全体の
 * エラーも入る**。件数として数えると分子が実態より大きくなる。
 *
 * ⚠️ **既存の `fetched` / `total` を分母に流用しない。** 取得件数と、
 * 実際に処理へ通した件数は一致しない（フィルタで落ちる）。
 * `syncStreamingMovies` では取得100件に対し配信判定に通すのが20件、
 * という状態が普通に起きる。薄まった失敗率は全滅を見逃す。
 */

/** 1件ずつ処理した結果の集計 */
export interface ItemOutcome {
  /** 失敗しうる処理に通した件数。フィルタで落とした分は含めない */
  attempted: number;
  /** そのうち失敗した件数。対象外としてスキップした分は含めない */
  failed: number;
}

/** 集計の初期値 */
export function createItemOutcome(): ItemOutcome {
  return { attempted: 0, failed: 0 };
}
