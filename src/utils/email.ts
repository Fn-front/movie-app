/**
 * メールアドレスの正規化
 *
 * DB の `users.email` は `VARCHAR(255) UNIQUE` で**大小文字を区別する**ため、
 * 正規化せずに扱うと `victim@example.com` と `Victim@example.com` が
 * 別アカウント・別レート制限カウンタになる。これにより、
 *
 * - 表記を変えるだけで送信上限・登録上限を回避し、同一メールボックスへ
 *   確認コードメールを無制限に送れる
 * - OAuth の「メール一致で既存アカウントへリンク」が表記違いで取りこぼし、
 *   同一人物の重複アカウントが黙って作られる
 *
 * といった問題が起きる。アプリに入ってくる全ての入口でこの関数を通し、
 * DB・レート制限識別子・OTPのHMAC入力には**常に正規化済みの値だけ**を使う。
 */

/**
 * メールアドレスを正規化する
 *
 * 前後の空白を落とし、小文字に揃えるだけに留める。
 *
 * ドット除去やプラスエイリアス除去（Gmail 固有の仕様）は**行わない**。
 * `user.name@example.com` と `username@example.com` を同一視すると、
 * これらを別アドレスとして扱う他のメールプロバイダで別人のアカウントを
 * 衝突させてしまうため。ドット違いによる多重送信は、識別子の正規化ではなく
 * 送信カウンタ側（実送信時のみ計上）で抑止する。
 *
 * @param email - 入力されたメールアドレス
 * @returns 正規化済みメールアドレス
 */
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}
