-- ============================================
-- Migration: スクリーンを下げ、下部の余白を減らす
-- ============================================
--
-- 直近20260516080958で screen_center_y=4.5→4.75、screen_height=7→6.5に
-- 変更したが、スクリーンの下に黒い壁（背面壁）が広く見える状態となった。
--
-- 観客視点でスクリーン下端と床の間の「無効領域」が大きいため、
-- スクリーンを下げて余白を減らす。
--
-- - screen_height: 6.5 → 7.0（元に戻す、シネスコ 16:7 ≈ 2.29:1）
-- - screen_center_y: 4.75 → 4.5
-- - 結果: 下端 y=1.0、上端 y=8.0
-- - 床から下端まで 1m の余白（前は 1.5m）
-- ============================================

UPDATE theaters
SET screen_height = 7.0,
    screen_center_y = 4.5
WHERE slug = 'standard-medium';
