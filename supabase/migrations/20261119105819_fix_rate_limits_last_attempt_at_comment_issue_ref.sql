--
-- なぜ 20261119102332 を直すのではなく追補を作るのか:
--   20261119102332 は **本番へ適用済みとして記録されている**
--   （supabase_migrations.schema_migrations に version が入っている）。
--   db push はバージョン単位でスキップするため、あのファイルを編集しても
--   本番には二度と反映されない。新規構築したDBだけが新しい文面になり、
--   本番とファイルが恒久的に食い違う。
--
-- 何が起きたか:
--   索引削除の作業中、Issue を起票する前に仮の番号 `#1318` でコメントを書き、
--   その状態で db push してしまった。あとからファイル側だけを正しい `#1326` に
--   直したので、本番には `#1318` が残った。`#1318` は
--   「レコメンド生成の除外集合が1000件で静かに打ち切られる」で**全くの別件**。
--   読んだ人が無関係な Issue に飛ばされる。
--
-- 教訓:
--   Issue 番号を本文に書くマイグレーションは、**番号が確定してから** push する。
--   COMMENT のような「上書きで直せるもの」ならこうして追補できるが、
--   DDL の本体を間違えた場合は打ち消しのマイグレーションが要る。
--
-- ⚠️ COMMENT ON COLUMN は上書きなので、20261019012324 が書いた
--   TIMESTAMPTZ 必須の理由を消さずに引き継ぐこと。

