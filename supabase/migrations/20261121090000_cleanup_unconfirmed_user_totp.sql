-- 設定途中のまま残っている第2要素を消す（#1368 のレビュー）
--
-- ⛔ `totp/setup` に再認証を足したが、**それ以前に作られた保留行には効かない**。
--
--    `totp/enable` は `setup` が作った保留行（`confirmed_at IS NULL`）だけを
--    見るため、再認証が入る前にセッションを奪って `setup` を1回叩いていれば、
--    修正後もその行をそのまま有効化できる。入口を塞いだ意味が無くなる。
--
--    保留行には TTL も掃除も無く、無期限に生きる。1回だけ掃除する。
--
-- ⚠️ 正規の利用者が設定途中なら、やり直してもらうことになる。保留行は
--    「QRを出したが6桁をまだ入れていない」状態で、有効化済み（`confirmed_at`
--    が入っている行）には**一切触れない**。ログインできなくなる利用者は出ない。
--
-- ⚠️ `totp_recovery_codes` は有効化のときにしか作られないので、ここで
--    消す行に紐づくものは存在しない。
DELETE FROM public.user_totp
WHERE confirmed_at IS NULL;
